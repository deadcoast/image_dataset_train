def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def snapshot(root: Path) -> dict[str, str]:
    return {p.relative_to(root).as_posix(): digest(p) for p in root.rglob("*") if p.is_file()}


def save(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def check_source_archive(wheel: Path) -> dict:
    archives = list(wheel.parent.glob("*.tar.gz"))
    if not archives:
        return {"source_archive_checked": False}
    if len(archives) != 1:
        raise ValueError("Use a build directory with exactly one source archive")
    archive_path = archives[0]
    with tarfile.open(archive_path) as archive, zipfile.ZipFile(wheel) as packaged:
        names = archive.getnames()
        prefix = names[0].split("/")[0]
        required = [
            "install.cmd",
            "install.ps1",
            "uv.lock",
            "pyproject.toml",
            "README.md",
            "docs/INSTALLATION.md",
            "scripts/package_smoke.py",
        ]
        for relative in required:
            member = archive.getmember(f"{prefix}/{relative}")
            if not member.isfile():
                raise ValueError(f"Source archive is missing a regular {relative}")
        matched = 0
        for name in packaged.namelist():
            if not name.startswith("image_dataset_train/") or name.endswith("/"):
                continue
            member = archive.getmember(f"{prefix}/src/{name}")
            stream = archive.extractfile(member)
            if not member.isfile() or stream is None or stream.read() != packaged.read(name):
                raise ValueError(f"Source archive/wheel payload mismatch: {name}")
            matched += 1
    return {
        "source_archive_checked": True,
        "source_archive": str(archive_path),
        "source_archive_sha256": digest(archive_path),
        "source_archive_payload_files": matched,
    }


class Commands:
    def __init__(self, root: Path, name="commands"):
        self.root, self.records, self.name = root, [], name
        self.logs = root / f"{name}-logs"
        self.logs.mkdir(exist_ok=True)

    def run(self, arguments, *, expect=0, timeout=180):
        arguments = list(map(str, arguments))
        index = len(self.records)
        started = time.perf_counter()
        result = subprocess.run(
            arguments,
            cwd=self.root,
            env=os.environ.copy(),
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )
        prefix = f"{index:03d}"
        for stream in ("stdout", "stderr"):
            (self.logs / f"{prefix}.{stream}.txt").write_text(
                getattr(result, stream), encoding="utf-8"
            )
        self.records.append(
            {
                "arguments": arguments,
                "exit_code": result.returncode,
                "elapsed_seconds": time.perf_counter() - started,
                "stdout": f"{self.logs.name}/{prefix}.stdout.txt",
                "stderr": f"{self.logs.name}/{prefix}.stderr.txt",
            }
        )
        save(self.root / f"{self.name}.json", self.records)
        if result.returncode != expect:
            raise AssertionError(
                f"Command exited {result.returncode}, expected {expect}: {arguments}\n"
                f"{result.stdout[-3000:]}\n{result.stderr[-3000:]}"
            )
        return result


