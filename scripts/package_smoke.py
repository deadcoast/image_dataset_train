def exercise_collection_review(commands, dataset, prepared, workspace, report):
    """Open the installed CLI's real server; GET-only checks cannot grant acceptance."""
    from image_dataset_train import qa as qa_module
    from image_dataset_train.assessments import PilotAssessment
    from image_dataset_train.config import load_config
    from image_dataset_train.qa import read_qa

    qa = Path(report["path"])
    metadata, data = read_qa(qa)
    config = load_config(Path(report["config_path"]))
    assessments = PilotAssessment(config.reviews, qa)
    before_assessment = assessments.read()
    assert assessments.summary(before_assessment)["human_accepted"] is False
    source = Path(prepared["source"])
    before_source, before_workspace = snapshot(source), snapshot(workspace)
    cli_arguments = [
        str(dataset),
        "collections",
        "review",
        "fixture [猫]",
        "--run",
        report["id"],
        "--expected-sha256",
        report["run_sha256"],
        "--no-open",
        "--port",
        "0",
    ]
    # Invoke the installed entry point without a launcher child. SIGBREAK otherwise
    # terminates Windows Python immediately instead of running the server's cleanup.
    bootstrap = (
        "import runpy, signal, sys; "
        "hasattr(signal, 'SIGBREAK') and "
        "signal.signal(signal.SIGBREAK, signal.default_int_handler); "
        "sys.argv[0] = 'dataset'; "
        "runpy.run_module('image_dataset_train', run_name='__main__')"
    )
    arguments = [sys.executable, "-u", "-c", bootstrap, *cli_arguments[1:]]
    options = {}
    if os.name == "nt":
        startup = subprocess.STARTUPINFO()
        startup.dwFlags |= subprocess.STARTF_USESHOWWINDOW
        startup.wShowWindow = subprocess.SW_HIDE
        options.update(startupinfo=startup, creationflags=subprocess.CREATE_NEW_PROCESS_GROUP)
    else:
        options["start_new_session"] = True
    prefix = f"{len(commands.records):03d}"
    stdout_path = commands.logs / f"{prefix}.stdout.txt"
    stderr_path = commands.logs / f"{prefix}.stderr.txt"
    started = time.perf_counter()
    url, process, stopped_cleanly = None, None, False
    opener = build_opener(ProxyHandler({}))  # Loopback must never use an ambient proxy.

    def fetch(relative):
        with opener.open(url + relative, timeout=5) as response:
            assert response.status == 200
            assert response.headers.get("Cache-Control") == "no-store"
            return response.read(), response.headers.get_content_type()

    with (
        stdout_path.open("w", encoding="utf-8") as stdout,
        stderr_path.open("w", encoding="utf-8") as stderr,
    ):
        try:
            process = subprocess.Popen(
                arguments,
                cwd=commands.root,
                env=os.environ.copy(),
                stdin=subprocess.DEVNULL,
                stdout=stdout,
                stderr=stderr,
                **options,
            )
            deadline = time.monotonic() + 30
            while time.monotonic() < deadline:
                output = stdout_path.read_text(encoding="utf-8", errors="replace")
                match = re.search(r"^Graphical reviewer: (\S+)$", output, re.MULTILINE)
                if match:
                    url = match.group(1)
                    break
                if process.poll() is not None:
                    raise AssertionError(f"Reviewer exited before serving: {output}")
                time.sleep(0.05)
            assert url is not None, "Reviewer did not publish its loopback URL"
            parsed = urlsplit(url)
            assert parsed.scheme == "http" and parsed.hostname == "127.0.0.1"
            assert (
                parsed.port and parsed.username is None and not parsed.query and not parsed.fragment
            )
            assert re.fullmatch(r"/[A-Za-z0-9_-]{24,}/", parsed.path)
            html, content_type = fetch("")
            assert content_type == "text/html" and b"Dataset pilot review" in html
            assert b"__QA_SCRIPT__" not in html and b"__QA_DATA__" not in html
            for name in ("qa_report.js", "qa_content.js", "qa_workflow.js", "qa_training.js"):
                script = Path(qa_module.__file__).with_name(name).read_text(encoding="utf-8")
                assert script.encode("utf-8") in html, f"Live reviewer omitted {name}"
            payload = re.search(
                rb'<script id="data" type="application/json">(.*?)</script>', html, re.S
            )
            assert payload and json.loads(payload.group(1))["entries"] == data["entries"]
            assessment_bytes, content_type = fetch("api/assessment")
            assert content_type == "application/json"
            assessment = json.loads(assessment_bytes)
            assert assessment["state"] == before_assessment
            assert assessment["summary"]["human_accepted"] is False
            preview = next(name for name in metadata["files"] if name.startswith("previews/"))
            preview_bytes, content_type = fetch(preview)
            assert content_type == "image/jpeg"
            assert hashlib.sha256(preview_bytes).hexdigest() == digest(qa / preview)
            entry = data["entries"][0]
            image_bytes, content_type = fetch("image/" + entry["id"])
            exported = Path(metadata["input_run"])
            row = next(
                json.loads(line)
                for line in (exported / "manifest.jsonl").read_text(encoding="utf-8").splitlines()
                if json.loads(line)["source_path"] == entry["source_path"]
            )
            assert content_type.startswith("image/")
            assert hashlib.sha256(image_bytes).hexdigest() == row["image_sha256"]
        finally:
            if process is not None and process.poll() is None:
                try:
                    process.send_signal(
                        signal.CTRL_BREAK_EVENT if os.name == "nt" else signal.SIGINT
                    )
                    process.wait(timeout=10)
                except (OSError, subprocess.TimeoutExpired):
                    if process.poll() is None:
                        process.terminate()
                        process.wait(timeout=5)
            stopped_cleanly = process is not None and process.returncode == 0
            commands.records.append(
                {
                    "arguments": arguments,
                    "cli_arguments": cli_arguments,
                    "exit_code": process.returncode if process is not None else None,
                    "elapsed_seconds": time.perf_counter() - started,
                    "stdout": f"{commands.logs.name}/{prefix}.stdout.txt",
                    "stderr": f"{commands.logs.name}/{prefix}.stderr.txt",
                    "owned_server_stopped_cleanly": stopped_cleanly,
                }
            )
            save(commands.root / f"{commands.name}.json", commands.records)
    assert stopped_cleanly, "Reviewer did not complete its owned-process shutdown"
    try:
        connection = socket.create_connection((parsed.hostname, parsed.port), timeout=1)
    except OSError:
        pass
    else:
        connection.close()
        raise AssertionError("Reviewer listener remained open after shutdown")
    assert snapshot(source) == before_source and snapshot(workspace) == before_workspace
    assert assessments.read() == before_assessment
    receipt = {
        "status": "passed",
        "scope": "generated fixture; GET-only live installed CLI server",
        "qa_record_id": report["id"],
        "qa_run_sha256": report["run_sha256"],
        "tokenized_loopback_url": url,
        "html_sha256": hashlib.sha256(html).hexdigest(),
        "preview_sha256": hashlib.sha256(preview_bytes).hexdigest(),
        "image_sha256": hashlib.sha256(image_bytes).hexdigest(),
        "html_preview_and_export_image_checked": True,
        "source_and_workspace_bytes_preserved": True,
        "assessment_unchanged": True,
        "human_acceptance": False,
        "browser_opened": False,
        "owned_server_stopped_cleanly": True,
        "listener_closed": True,
    }
    save(commands.root / "collection-review-handoff.json", receipt)
    return receipt


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--wheel",
        required=True,
        type=Path,
        help="Wheel file or directory containing exactly one wheel",
    )
    parser.add_argument("--constraints", type=Path, help="Locked uv requirements export")
    parser.add_argument("--workspace", type=Path, help="New directory; retained after the check")
    parser.add_argument("--uv", default=shutil.which("uv"))
    parser.add_argument("--require-catalog", action="store_true")
    parser.add_argument("--installed", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    wheel = args.wheel.resolve(strict=True)
    if wheel.is_dir():
        wheels = list(wheel.glob("*.whl"))
        if len(wheels) != 1:
            parser.error("The wheel directory must contain exactly one .whl file")
        wheel = wheels[0]
    root = (
        args.workspace.resolve()
        if args.workspace
        else Path(tempfile.mkdtemp(prefix="trainime-wheel-"))
    )
    if args.installed:
        try:
            result = exercise(root, wheel, require_catalog=args.require_catalog)
            save(root / "result.json", result)
            print(json.dumps(result, ensure_ascii=False, indent=2))
            return 0
        except BaseException as exc:
            save(
                root / "result.json",
                {"status": "failed", "error": str(exc), "traceback": traceback.format_exc()},
            )
            raise
    if args.workspace:
        root.mkdir(parents=True, exist_ok=False)
    if not args.uv or not args.constraints:
        parser.error(
            "Provide --constraints from uv export; uv must be installed or supplied with --uv"
        )
    constraints = args.constraints.resolve(strict=True)
    source_archive = check_source_archive(wheel)
    os.environ.pop("PYTHONPATH", None)
    os.environ.pop("PYTHONHOME", None)
    os.environ.pop("VIRTUAL_ENV", None)
    os.environ.update(
        TRAINIME_HOME=str(root / "application data"),
        PYTHONUTF8="1",
        NO_COLOR="1",
        HF_HUB_OFFLINE="1",
    )
    setup = Commands(root, "setup")
    environment = root / "isolated environment"
    setup.run([args.uv, "venv", "--python", sys.executable, environment])
    python = environment / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    setup.run(
        [
            args.uv,
            "pip",
            "install",
            "--python",
            python,
            "--constraint",
            constraints,
            "--link-mode",
            "copy",
            "--cache-dir",
            root / "uv cache",
            f"{wheel}[tag-cpu]",
        ],
        timeout=600,
    )
    save(
        root / "setup.json",
        {
            "wheel_sha256": digest(wheel),
            "constraints_sha256": digest(constraints),
            **source_archive,
            "commands": setup.records,
        },
    )
    shutil.copyfile(Path(__file__).resolve(), root / "smoke_worker.py")
    worker_args = [
        str(python),
        "-X",
        "utf8",
        "-I",
        str(root / "smoke_worker.py"),
        "--installed",
        "--wheel",
        str(wheel),
        "--workspace",
        str(root),
    ]
    if args.require_catalog:
        worker_args.append("--require-catalog")
    result = subprocess.run(worker_args, cwd=root)
    print(f"Installed-wheel evidence: {root}")
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
