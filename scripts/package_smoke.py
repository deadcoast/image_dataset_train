    from image_dataset_train.config import Config, ExportConfig, ValidationConfig
    from image_dataset_train.preparation import preparation_config, prepare_directory
    from image_dataset_train.reviews import ReviewStore, review_image, review_link

    fixture = root / "review history fixture"
    source, workspace = fixture / "source [猫]", fixture / "prepared"
    source.mkdir(parents=True)
    for index, name in enumerate(["one", "two", "three"]):
        image = Image.new("RGB", (256, 256), (40 * index, 150, 170))
        ImageDraw.Draw(image).rectangle((20 + index * 30, 10, 100, 200), fill="white")
        image.save(source / f"{name}.png")
        (source / f"{name}.txt").write_text(f"original {name} caption", encoding="utf-8")
    config = preparation_config(
        source,
        workspace,
        base=Config(
            source=source,
            runs=workspace / "runs",
            validation=ValidationConfig(min_short_side=8),
            reviews=workspace / "reviews",
            models=fixture / "models",
            scores=fixture / "scores",
            exports=workspace / "exports",
            export=ExportConfig(resolution=256),
        ),
    )
