def exercise_saved_rule_contract(commands, dataset, config_path, config, scored, workspace):
    """Reject inconsistent saved rules before evaluation or exposure publication."""
    from copy import deepcopy

    from image_dataset_train.caption_explanations import explain_caption
    from image_dataset_train.label_review_ui import LabelReviewSession

    metadata = scored / "run.json"
    original = metadata.read_bytes()
    judgment_path = workspace.directory / "judgments.json"
    original_judgments = judgment_path.read_bytes()
    source_before, run_before = snapshot(config.source), snapshot(scored)
    image = "alias.png"
    content = next(
        digest
        for digest, member in workspace.members.items()
        if any(alias["source_path"] == image for alias in member["aliases"])
    )
    evaluate = [
        dataset,
        "tag-evaluate",
        "--workspace",
        workspace.directory,
        "--run",
        scored,
        "--include-assistant",
        "--config",
        config_path,
        "--json",
    ]

    def compare():
        return LabelReviewSession(config, workspace.directory, [scored]).compare(
            {
                "image": content,
                "expected_revision": workspace.read()["revision"],
                "reviewer": "Synthetic contract assistant",
                "reviewer_kind": "assistant",
            }
        )

    records = []
    try:
        valid = json.loads(commands.run(evaluate).stdout)
        assert valid["human_accepted"] is False
        compared = compare()
        assert compared["models"][0]["thresholds"]["geometric_shape"] == 0.5
        assert explain_caption(scored, image)["status"] == "available"
        judgment_path.write_bytes(original_judgments)
        for kind in ("missing_rules", "null_rules", "wrong_digest", "unsupported_version"):
            altered = deepcopy(json.loads(original))
            if kind == "missing_rules":
                del altered["caption_rules"]
            elif kind == "null_rules":
                altered["caption_rules"] = None
            elif kind == "wrong_digest":
                altered["caption_rules_sha256"] = "0" * 64
            else:
                altered["caption_version"] = "future-caption-contract"
            save(metadata, altered)
            before = snapshot(config.runs), judgment_path.read_bytes()
            commands.run(evaluate, expect=2)
            try:
                compare()
            except ValueError as exc:
                error = str(exc)
            else:
                raise AssertionError(f"Invalid {kind} was compared")
            try:
                explanation = explain_caption(scored, image)
            except ValueError:
                assert kind in {"null_rules", "wrong_digest"}
            else:
                assert kind in {"missing_rules", "unsupported_version"}
                assert explanation["status"] == "unavailable"
            assert (snapshot(config.runs), judgment_path.read_bytes()) == before
            records.append(
                {"case": kind, "evaluation_and_comparison_rejected": True, "error": error}
            )
            metadata.write_bytes(original)
        recovered = compare()
        assert recovered["models"][0]["thresholds"]["geometric_shape"] == 0.5
    finally:
        metadata.write_bytes(original)
        judgment_path.write_bytes(original_judgments)
    assert snapshot(config.source) == source_before and snapshot(scored) == run_before
    assert judgment_path.read_bytes() == original_judgments
    receipt = {
        "status": "passed",
        "scored_run": str(scored),
        "workspace": str(workspace.directory),
        "cases": records,
        "source_scores_and_judgments_preserved": True,
        "valid_saved_threshold": 0.5,
        "restored_comparison_passed": True,
        "inference_performed": False,
        "human_acceptance": False,
    }
    save(commands.root / "saved-rule-contract.json", receipt)
    return receipt


def exercise_judgment_integrity(root, config, report, workspace):
    """Installed HTTP validation, failed-save preservation and explicit recovery."""
    from threading import Thread
    from urllib.error import HTTPError
    from urllib.request import Request

    from image_dataset_train.assessments import PilotAssessment
    from image_dataset_train.label_review_ui import make_label_server
    from image_dataset_train.review_ui import make_server
    from image_dataset_train.reviews import ReviewStore

    assessment = PilotAssessment(config.reviews, report)
    reviews = ReviewStore(config.reviews, config.source)
    paths = [assessment.path, reviews.path, workspace.directory / "judgments.json"]
    originals = {path: path.read_bytes() for path in paths}
    source_before, report_before = snapshot(config.source), snapshot(report)
    records = []
    opener = build_opener(ProxyHandler({}))

    def request(server, route, payload=None, *, expect=200):
        options = (
            {}
            if payload is None
            else {
                "data": json.dumps(payload).encode(),
                "headers": {
                    "Origin": f"http://{server.authority}",
                    "Content-Type": "application/json",
                },
            }
        )
        try:
            response = opener.open(Request(server.url + route, **options), timeout=20)
        except HTTPError as error:
            response = error
        with response:
            raw = response.read()
            assert response.status == expect, (route, response.status, raw)
            assert response.headers["Cache-Control"] == "no-store"
        records.append(
            {
                "route": route,
                "method": "GET" if payload is None else "POST",
                "status": expect,
                "sha256": hashlib.sha256(raw).hexdigest(),
            }
        )
        return json.loads(raw)

    def altered(path, change):
        state = json.loads(originals[path])
        change(state)
        save(path, state)
        return path.read_bytes()

    with (
        make_server(config, report) as server,
        make_label_server(config, workspace.directory) as label,
    ):
        workers = [Thread(target=item.serve_forever, daemon=True) for item in (server, label)]
        for worker in workers:
            worker.start()
        try:
            good = request(server, "api/assessment")
            assert good["summary"]["human_accepted"] is False
            entry = next(iter(assessment.entries.values()))
            image_route = "api/review/" + entry["id"]
            review = request(server, image_route)
            labels = request(label, "api/state")
            image = labels["members"][0]["sha256"]
            label_payload = {
                "image": image,
                "expected_revision": labels["revision"],
                "judgments": [
                    {
                        "label": labels["labels"][0],
                        "value": "uncertain",
                        "notes": "Generated installed API fixture only",
                        "reviewer": "Synthetic assistant",
                        "reviewer_kind": "assistant",
                    }
                ],
            }
            # Current state cannot override the history's original attribution.
            damaged = altered(
                assessment.path, lambda state: state["conclusion"].update(reviewer_kind="human")
            )
            assert request(server, "api/assessment", expect=400)["error"]
            assert request(
                server,
                "api/assessment",
                {
                    "expected_revision": good["state"]["revision"],
                    "verdict": "unreviewed",
                    "reviewer": "Synthetic assistant",
                    "reviewer_kind": "assistant",
                    "notes": "Must reject inconsistent evidence",
                },
                expect=400,
            )["error"]
            assert assessment.path.read_bytes() == damaged
            assessment.path.write_bytes(originals[assessment.path])
            assert request(server, "api/assessment") == good

            damaged = altered(
                reviews.path,
                lambda state: next(iter(state["images"].values())).update(
                    reason="Generated unrecorded current-only edit"
                ),
            )
            for route in (image_route, "api/pairs?decision=all", "api/review-changes"):
                assert request(server, route, expect=400)["error"]
            assert request(
                server,
                image_route,
                {
                    "expected_revision": review["revision"],
                    "reason": "Must not append to inconsistent history",
                    "caption": "Generated edit",
                },
                expect=400,
            )["error"]
            assert reviews.path.read_bytes() == damaged
            reviews.path.write_bytes(originals[reviews.path])
            assert request(server, image_route) == review

            label_path = paths[2]
            damaged = altered(label_path, lambda state: state["history"][0].update(actor=None))
            assert request(label, "api/state", expect=400)["error"]
            assert request(label, "api/save", label_payload, expect=400)["error"]
            assert label_path.read_bytes() == damaged
            label_path.write_bytes(originals[label_path])
            assert request(label, "api/state") == labels
            saved = request(label, "api/save", label_payload)
            assert saved["revision"] == labels["revision"] + 1
            assert saved["judgments"][image][labels["labels"][0]]["reviewer_kind"] == "assistant"
            assert request(label, "api/save", label_payload, expect=409)["error"]
            label_payload["expected_revision"] = saved["revision"]
            label_payload["judgments"][0]["value"] = "absent"
            assert request(label, "api/save", label_payload)["revision"] == saved["revision"] + 1
        finally:
            for path, raw in originals.items():
                path.write_bytes(raw)
            for item in (server, label):
                item.shutdown()
            for worker in workers:
                worker.join(timeout=5)
                assert not worker.is_alive()
    assert snapshot(config.source) == source_before and snapshot(report) == report_before
    assert all(path.read_bytes() == raw for path, raw in originals.items())
    result = {
        "status": "passed",
        "http_requests": len(records),
        "http_records": records,
        "invalid_evidence_preserved": True,
        "explicit_restoration_recovers": True,
        "assistant_api_save_conflict_retry": True,
        "source_report_records_preserved": True,
        "human_acceptance": False,
        "browser_rendered": False,
    }
    save(root / "judgment-integrity-http.json", result)
    return result


def exercise(root: Path, wheel: Path, *, require_catalog=False) -> dict:
    from PIL import Image, ImageDraw

    import image_dataset_train
    from image_dataset_train.implementation import (
        PAYLOAD_SUFFIXES,
        implementation_identity,
        validate_implementation_identity,
    )
    from image_dataset_train.repair_package import restore

    package = Path(image_dataset_train.__file__).resolve().parent
    if not package.is_relative_to(Path(sys.prefix).resolve()):
        raise AssertionError(f"Package was imported outside the isolated environment: {package}")
    binary = Path(sys.executable).parent
    suffix = ".exe" if os.name == "nt" else ""
    trainime, dataset = binary / f"trainime{suffix}", binary / f"dataset{suffix}"
    commands = Commands(root)
    home = Path(os.environ["TRAINIME_HOME"])
    required = {
        "qa_report.html",
        "qa_report.js",
        "qa_content.js",
        "qa_training.js",
        "qa_workflow.js",
        "qa_preferences.js",
        "trainer-requirements.txt",
        "trainer-requirements.in",
    }
    with zipfile.ZipFile(wheel) as archive:
        payload = {
            name: archive.read(name)
            for name in archive.namelist()
            if name.startswith("image_dataset_train/") and not name.endswith("/")
        }
    if not required <= {Path(name).name for name in payload}:
        raise AssertionError("The wheel is missing required reviewer/trainer resources")

    def verify_payload():
        for name, raw in payload.items():
            if package.parent.joinpath(*name.split("/")).read_bytes() != raw:
                raise AssertionError(f"Installed payload differs from wheel: {name}")

    verify_payload()
    implementation = implementation_identity()
    validate_implementation_identity(implementation)
    assert implementation["version"] == image_dataset_train.__version__
    assert implementation["files"] == {
        name.removeprefix("image_dataset_train/"): hashlib.sha256(raw).hexdigest()
        for name, raw in payload.items()
        if Path(name).suffix in PAYLOAD_SUFFIXES and "__pycache__" not in Path(name).parts
    }
    commands.run([trainime, "--version"])
    commands.run([dataset, "--version"])
    commands.run([dataset, "--help"])
    commands.run([trainime, "doctor", "--runtime-only", "--dryrun", "--json"])

    launchers_before = {str(p): digest(p) for p in (trainime, dataset)}
    damaged = ["qa_report.html", "qa_content.js", "trainer-requirements.txt", "captions.py"]
    home.mkdir(parents=True, exist_ok=True)
    save(
        home / "install.json",
        {
            "wheel": str(wheel),
            "wheel_sha256": digest(wheel),
            "bin": str(binary),
            "path_registered": False,
        },
    )
    for name in damaged[:-1]:
        (package / name).write_bytes(b"simulated broken package payload\n")
    checked = commands.run([trainime, "doctor", "--dryrun", "--json"], expect=1)
    checks = {item["name"]: item for item in json.loads(checked.stdout)["checks"]}
    assert checks["runtime"]["status"] == "ok" and checks["package"]["status"] == "error"
    (package / damaged[-1]).write_bytes(b"simulated broken package payload\n")
    assert restore(wheel, package.parent) == len(damaged)
    assert restore(wheel, package.parent) == 0
    verify_payload()
    assert {str(p): digest(p) for p in (trainime, dataset)} == launchers_before
    repair_receipts = list((home / "recovery/application").glob("*/repair.json"))
    assert len(repair_receipts) == 1
    repair = json.loads(repair_receipts[0].read_text(encoding="utf-8"))
