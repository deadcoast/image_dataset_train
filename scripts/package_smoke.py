def exercise_model_binding(root, config, model, inspect):
    """Installed configured-slot rejection and preservation through model repair."""
    from image_dataset_train.doctor import repair_model
    from image_dataset_train.model_bundle import bundle_path, fingerprint, load_bundle

    metadata = model / "model.json"
    original = metadata.read_bytes()
    before = snapshot(config.models)
    cases = []
    try:
        for field, value in (
            ("model", "eva02-large-v3"),
            ("repo", "generated-foreign/repository"),
            ("revision", "b" * 40),
        ):
            altered = json.loads(original)
            altered[field] = value
            altered["artifact_id"] = fingerprint(
                {key: altered[key] for key in ("repo", "revision", "files")}
            )
            save(metadata, altered)
            assert load_bundle(model).metadata == altered  # Generic artifact inspection.
            _, unavailable = inspect(expect=1)
            assert unavailable["status"] == "unavailable" and unavailable["counts"] is None
            assert unavailable["reason"] == "model_unavailable"
            assert "selection mismatch" in unavailable["error"]["message"]
            assert json.loads(metadata.read_bytes()) == altered
            cases.append({"mismatch": field, "read_only_status_rejected": True})
    finally:
        metadata.write_bytes(original)
    assert snapshot(config.models) == before

    # Recovery operates in its own generated app home and retains the foreign
    # bytes. Its injected fetch copies our tiny graph rather than using a network.
    home = root / "model binding recovery home"
    destination = bundle_path(home / "models", config.tagging.model)
    shutil.copytree(model, destination)
    altered = json.loads(original)
    altered["repo"] = "generated-foreign/recovery"
    altered["artifact_id"] = fingerprint(
        {key: altered[key] for key in ("repo", "revision", "files")}
    )
    save(destination / "model.json", altered)
    foreign = snapshot(destination)
    fetched = []

    def fetch(model_root, name):
        assert model_root == home / "models" and name == config.tagging.model
        fetched.append(name)
        shutil.copytree(model, destination)
        return destination

    repaired = repair_model(home, fetch=fetch)
    assert fetched == [config.tagging.model]
    assert load_bundle(repaired, model=config.tagging.model).metadata == json.loads(original)
    backup = next((home / "recovery" / "models").iterdir())
    assert snapshot(backup) == foreign
    assert repair_model(home, fetch=fetch) == repaired and len(fetched) == 1
    assert snapshot(config.models) == before
    receipt = {
        "status": "passed",
        "mismatches": cases,
        "generic_inspection_preserved": True,
        "configured_status_rejected_before_inference": True,
        "recovery_backup": str(backup),
        "recovery_preserved_foreign_bytes": True,
        "matching_reuse_avoids_fetch": True,
        "models_downloaded": False,
        "human_acceptance": False,
    }
    save(root / "model-binding-contract.json", receipt)
    return receipt


